def resolve_cell_verilog(
    *, cell_library: str, pdk_variant: str | None, pdk_root: str | None
) -> list[str]:
    """The PDK's own Verilog simulation models for ``cell_library``, in
    compile order (primitives first).

    These carry the ``specify`` blocks whose all-zero placeholder delays
    (``(A =>  X) = (0:0:0, 0:0:0);``) SDF back-annotation overwrites -- the
    reason a gate-level sim can be zero-delay and SDF-annotated from the
    *same* model files.
    """
    from klayout_tools.pdk import PdkNotFoundError, find_pdk

    try:
        payload = find_pdk(pdk_variant, pdk_root)
    except PdkNotFoundError as exc:
        raise SpikeError(str(exc)) from exc

    libs_ref = payload["assets"].get("libs_ref")
    if not libs_ref:
        raise SpikeError(
            f"PDK '{payload['variant']}' at {payload['root']} ships no libs.ref/ "
            "-- no Verilog cell models to simulate against"
        )
    verilog_dir = os.path.join(libs_ref, cell_library, "verilog")
    models = [
        os.path.join(verilog_dir, "primitives.v"),
        os.path.join(verilog_dir, f"{cell_library}.v"),
    ]
    missing = [path for path in models if not os.path.isfile(path)]
    if missing:
        raise SpikeError(
            "PDK install is missing the cell-library Verilog models this spike "
            f"needs: {', '.join(missing)}"
        )
    return models


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--rtl",
        default=os.path.join(REPO_ROOT, "examples/functional-verification/gcd.v"),
        help="original RTL source (the baseline run)",
    )
    parser.add_argument(
        "--netlist",
        default=os.path.join(REPO_ROOT, "tests/corpus/statime/gcd_netlist.v"),
        help="gate-level netlist (klt synthesize's netlist_path convention)",
    )
    parser.add_argument("--hdl-toplevel", default="gcd")
    parser.add_argument("--testbench-module", default="test_gcd")
    parser.add_argument(
        "--testbench-dir",
        default=os.path.join(REPO_ROOT, "examples/functional-verification"),
        help="directory containing <testbench-module>.py",
    )
    parser.add_argument("--cell-library", default="sky130_fd_sc_hd")
    parser.add_argument("--cell-prefix", default=None, help="default: <cell-library>__")
    parser.add_argument("--pdk", default=os.environ.get("PDK", "sky130A"))
    parser.add_argument("--pdk-root", default=None)
    parser.add_argument(
        "--delay-ns",
        type=float,
        nargs="+",
        default=[0.1, 0.5, 0.7, 0.9, 2.0],
        help="per-stage SDF delays to sweep (one annotated run each)",
    )
    parser.add_argument("--random-seed", type=int, default=1)
    parser.add_argument(
        "--work-dir", default=None, help="default: a fresh temporary directory"
    )
    parser.add_argument(
        "--fail-on-sdf-diagnostics",
        action="store_true",
        help=(
            "exit nonzero if any annotated run emitted an SDF WARNING/ERROR "
            "(recommended: Icarus keeps going and exits 0 after skipping an "
            "annotation, so a clean-looking PASS can mean nothing was applied)"
        ),
    )
    parser.add_argument("--format", choices=("text", "json"), default="text")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    if shutil.which("iverilog") is None:
        print("ERROR: iverilog not found on $PATH", file=sys.stderr)
        return 1

    cell_prefix = args.cell_prefix or f"{args.cell_library}__"
    work_dir = args.work_dir or tempfile.mkdtemp(prefix="klt-sdf-spike-")
    os.makedirs(work_dir, exist_ok=True)

    try:
        models = resolve_cell_verilog(
            cell_library=args.cell_library, pdk_variant=args.pdk, pdk_root=args.pdk_root
        )
        cells = parse_instances(args.netlist, cell_prefix)

        common = {
            "hdl_toplevel": args.hdl_toplevel,
            "testbench_module": args.testbench_module,
            "testbench_dir": os.path.abspath(args.testbench_dir),
            "work_dir": work_dir,
            "timescale": ("1ns", "1ps"),
            "random_seed": args.random_seed,
        }

        runs = [
            run_regression(label="rtl", sources=[args.rtl], build_args=[], **common),
            run_regression(
                label="gate-level",
                sources=[args.netlist, *models],
                build_args=[],
                **common,
            ),
            # Control isolating the build flags from the annotation itself:
            # the PDK's own specify blocks carry all-zero placeholder delays,
            # so enabling them without an SDF must leave every verdict
            # identical to the zero-delay run. Any change here would mean the
            # sweep below is measuring `-gspecify`, not `$sdf_annotate`.
            run_regression(
                label="gl+specify",
                sources=[args.netlist, *models],
                build_args=list(SDF_BUILD_FLAGS),
                **common,
            ),
        ]
        for delay_ns in args.delay_ns:
            tag = f"{delay_ns:.3f}".replace(".", "p")
            sdf_path = os.path.join(work_dir, f"annotate_{tag}.sdf")
            shim_path = os.path.join(work_dir, f"shim_{tag}.v")
            with open(sdf_path, "w", encoding="utf-8") as handle:
                handle.write(
                    generate_sdf(cells, design=args.hdl_toplevel, delay_ns=delay_ns)
                )
            write_annotate_shim(
                shim_path, sdf_path=sdf_path, hdl_toplevel=args.hdl_toplevel
            )
            runs.append(
                run_regression(
                    label=f"sdf-{tag}",
                    sources=[args.netlist, shim_path, *models],
                    build_args=[*SDF_BUILD_FLAGS, "-s", "klt_sdf_annotate"],
                    **common,
                )
            )

        payload = {
            "design": args.hdl_toplevel,
            "netlist": os.path.abspath(args.netlist),
            "cell_library": args.cell_library,
            "cell_instances": len(cells),
            "iverilog_version": _iverilog_version(),
            "work_dir": work_dir,
            "runs": runs,
        }
    except SpikeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.format == "json":
        print(json.dumps(payload, indent=2))
    else:
        _print_text(payload)

    if args.fail_on_sdf_diagnostics:
        noisy = [
            run
            for run in runs
            if run["label"].startswith("sdf-") and run["sdf_diagnostics"]
        ]
        if noisy:
            for run in noisy:
                for line in run["sdf_diagnostics"]:
                    print(f"SDF diagnostic in {run['label']}: {line}", file=sys.stderr)
            return 1
    return 0


def _iverilog_version() -> str | None:
    try:
        completed = subprocess.run(["iverilog", "-V"], capture_output=True, text=True)
    except OSError:
        return None
    match = re.search(
        r"Icarus Verilog version (\S+)", completed.stdout + completed.stderr
    )
    return match.group(1) if match else None


def _print_text(payload: dict[str, Any]) -> None:
    print(
        f"design={payload['design']} netlist={payload['netlist']} "
        f"cells={payload['cell_instances']} iverilog={payload['iverilog_version']}"
    )
    print(f"artifacts: {payload['work_dir']}")
    names = [test["name"] for test in payload["runs"][0]["tests"]]
    width = max(len(name) for name in names)
    header = "run".ljust(14) + "  " + "  ".join(name.ljust(width) for name in names)
    print()
    print(header + "  sdf-diags  no-timing-check")
    print("-" * len(header) + "  ---------  ---------------")
    for run in payload["runs"]:
        verdicts = {test["name"]: test["status"] for test in run["tests"]}
        row = (
            run["label"].ljust(14)
            + "  "
            + "  ".join(verdicts.get(name, "-").ljust(width) for name in names)
        )
        diags = len(run["sdf_diagnostics"])
        print(f"{row}  {diags:>9}  {run['timing_check_warnings']:>15}")


if __name__ == "__main__":  # pragma: no cover - operator-run script
    raise SystemExit(main())
