#!/usr/bin/env python3
"""Static-typing ratchet, not a ceiling (issue #3221).

`mypy` over `src/` reports hundreds of pre-existing diagnostics. Fixing them
all at once is out of scope, and a bare "zero errors" gate would be red from
day one. This script is the ratchet, mirroring
`scripts/check_complexity_baseline.py`:

1. `type-baseline.json` (repo root) records every diagnostic present on the
   day the ratchet landed, as a count per `(file, error-code, message)` --
   generated by this exact script (`--update-baseline`) so local and CI
   output cannot drift apart.
2. Default (check) mode re-runs mypy and fails when (a) a `(file, code,
   message)` key is absent from the baseline, or (b) a baselined key now
   occurs *more* times than recorded. A key whose count decreases or that
   disappears never fails: that is improvement, and the baseline need not be
   re-tightened on every touch.

Keys deliberately exclude line and column numbers: unrelated edits shift
them constantly and would make the ratchet fail on changes that never
touched the flagged code.

The baseline must be generated with the project's dependencies installed
(`uv run --extra dev python scripts/check_type_baseline.py ...`), otherwise
`import-not-found` / `import-untyped` noise would be baselined. This script
refuses to run (check or update) when it sees such diagnostics.

Usage::

    # check against the committed baseline (CI's step)
    uv run --frozen --extra dev python scripts/check_type_baseline.py

    # regenerate after intentionally fixing diagnostics (or, with reviewer
    # sign-off, accepting new ones)
    uv run --frozen --extra dev python scripts/check_type_baseline.py --update-baseline
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_BASELINE_PATH = REPO_ROOT / "type-baseline.json"
BASELINE_SCHEMA_VERSION = 1

# Environment problems, not code problems: the baseline must never absorb them.
ENVIRONMENT_CODES = frozenset({"import-not-found", "import-untyped"})

Key = tuple[str, str, str]  # (file, error code, message)


def _mypy_version() -> str:
    result = subprocess.run(
        [sys.executable, "-m", "mypy", "--version"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def parse_mypy_json(stdout: str) -> Counter[Key]:
    """Count diagnostics per `(file, code, message)` from `mypy --output json`.

    Only `severity == "error"` entries count; notes carry no code and are
    context for the preceding error.
    """
    counts: Counter[Key] = Counter()
    for line in stdout.splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        entry = json.loads(line)
        if entry.get("severity") != "error":
            continue
        file = Path(entry["file"]).as_posix()
        counts[(file, entry.get("code") or "", entry["message"])] += 1
    return counts


def run_mypy(paths: list[str] | None = None) -> Counter[Key]:
    cmd = [sys.executable, "-m", "mypy", "--output", "json", "--no-error-summary"]
    if paths:
        cmd.extend(paths)
    result = subprocess.run(
        cmd, cwd=REPO_ROOT, capture_output=True, text=True, check=False
    )
    # mypy exits 1 when it reports errors -- the expected outcome here.
    if result.returncode not in (0, 1):
        raise RuntimeError(
            f"mypy exited {result.returncode}\n"
            f"stdout: {result.stdout}\nstderr: {result.stderr}"
        )
    return parse_mypy_json(result.stdout)


def environment_problems(counts: Counter[Key]) -> list[Key]:
    return sorted(k for k in counts if k[1] in ENVIRONMENT_CODES)


def load_baseline(path: Path) -> Counter[Key]:
    if not path.exists():
        return Counter()
    data = json.loads(path.read_text(encoding="utf-8"))
    baseline: Counter[Key] = Counter()
    for entry in data.get("diagnostics", []):
        baseline[(entry["file"], entry["code"], entry["message"])] += entry["count"]
    return baseline


def write_baseline(path: Path, counts: Counter[Key]) -> None:
    data = {
        "schema_version": BASELINE_SCHEMA_VERSION,
        "generated_by": (
            f"scripts/check_type_baseline.py --update-baseline ({_mypy_version()})"
        ),
        "diagnostics": [
            {"file": f, "code": c, "message": m, "count": n}
            for (f, c, m), n in sorted(counts.items())
        ],
    }
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def compare(
    current: Counter[Key], baseline: Counter[Key]
) -> tuple[list[tuple[Key, int]], list[tuple[Key, int, int]]]:
    """Return `(new, increased)`; decreases and removals never fail."""
    new: list[tuple[Key, int]] = []
    increased: list[tuple[Key, int, int]] = []
    for key, count in sorted(current.items()):
        base = baseline.get(key, 0)
        if base == 0:
            new.append((key, count))
        elif count > base:
            increased.append((key, base, count))
    return new, increased


def _fail(summary: str) -> None:
    print(f"::error::{summary}", file=sys.stderr)
    print(summary, file=sys.stderr)


def _refuse_environment_noise(counts: Counter[Key]) -> int | None:
    problems = environment_problems(counts)
    if not problems:
        return None
    _fail(
        f"{len(problems)} diagnostic(s) look like a missing-dependency problem "
        "(import-not-found / import-untyped); run via "
        "`uv run --frozen --extra dev` so project dependencies are installed:"
    )
    for file, code, message in problems[:10]:
        print(f"  {file}: [{code}] {message}")
    return 2


def _cmd_check(args: argparse.Namespace) -> int:
    current = run_mypy(args.paths)
    refused = _refuse_environment_noise(current)
    if refused is not None:
        return refused
    baseline = load_baseline(args.baseline)
    new, increased = compare(current, baseline)

    if new:
        _fail(f"{len(new)} new type diagnostic(s) not in {args.baseline.name}:")
        for (file, code, message), count in new:
            suffix = f" (x{count})" if count > 1 else ""
            print(f"  {file}: [{code}] {message}{suffix}")
    if increased:
        _fail(f"{len(increased)} baselined type diagnostic(s) occur MORE often:")
        for (file, code, message), base, curr in increased:
            print(f"  {file}: [{code}] {message} ({base} -> {curr})")
    if new or increased:
        print(
            "\nFix the new diagnostics. If accepting them is the right call, "
            "with reviewer sign-off, refresh the baseline:\n"
            "  uv run --frozen --extra dev python "
            "scripts/check_type_baseline.py --update-baseline",
            file=sys.stderr,
        )
        return 1

    print(
        f"OK: no type diagnostics beyond the {sum(baseline.values())} baselined in "
        f"{args.baseline.name} ({sum(current.values())} currently reported)."
    )
    return 0


def _cmd_update_baseline(args: argparse.Namespace) -> int:
    current = run_mypy(args.paths)
    refused = _refuse_environment_noise(current)
    if refused is not None:
        return refused
    write_baseline(args.baseline, current)
    print(f"Wrote {sum(current.values())} diagnostic(s) to {args.baseline}.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "paths",
        nargs="*",
        help="paths to check (default: mypy's configured `files`, i.e. src)",
    )
    parser.add_argument(
        "--baseline",
        type=Path,
        default=DEFAULT_BASELINE_PATH,
        help=f"baseline JSON file path (default: {DEFAULT_BASELINE_PATH.name})",
    )
    parser.add_argument(
        "--update-baseline",
        action="store_true",
        help="regenerate the baseline from current mypy output instead of checking",
    )
    args = parser.parse_args(argv)
    if args.update_baseline:
        return _cmd_update_baseline(args)
    return _cmd_check(args)


if __name__ == "__main__":
    raise SystemExit(main())
