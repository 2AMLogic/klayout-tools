"""Netlist pre-flight: behavioural `reg`/`always` latch (issue #5792).

When the synthesis library has no latch cell at all, a surviving gate-level
latch primitive (`$_DLATCH_*_`) has no mapping target -- `write_verilog`
then renders it behaviourally (a `reg` declaration plus an `always @*`
block; verified live, Yosys 0.67), and OpenSTA's structural reader rejects
that shape as a bare `[ERROR STA-0171] <netlist> line N, syntax error` at
the floorplan stage. The pre-flight names the construct, the line, and the
latch-has-no-library-cell fix instead.

Issue #6274 split the message's *construct* clause (always: construct, line,
offending text) from its *cause* clause (the latch narrative, only when the
netlist actually carries Yosys's unmapped-latch rendering -- a level-sensitive
`always @*` whose body is a bare `if (...)`; anything else, e.g. an RTL source
file handed over as the netlist, gets a generic "behavioural Verilog, not a
structural netlist" clause), and widened the pre-flight pattern to the
SystemVerilog `always_ff`/`always_comb`/`always_latch` and `initial` forms.

Focused sibling of `test_place_and_route.py` (same split as
`test_synthesize.py`/`test_synthesize_latch_warning.py`); the fixtures come
from the parent module so both suites exercise the same netlist shape.
"""

import pytest

from klayout_tools import netlist_construct_scan, place_and_route
from test_place_and_route import _CLEAN_NETLIST, _reject_message, _write

#: The shape real Yosys 0.67 `write_verilog -noattr` writes for unmapped
#: latches (verified live for issue #6274): every `reg` declaration sits in
#: the declaration block, and the `always @*` blocks come *later* -- the two
#: are **not** adjacent -- so the latch evidence cannot be an adjacency rule.
_YOSYS_UNMAPPED_LATCH_NETLIST = """\
/* Generated by Yosys 0.67+post */

module lat(en, d, clk, q, q2, r);
  input en;
  wire en;
  input d;
  wire d;
  input clk;
  wire clk;
  output q;
  reg q;
  output q2;
  reg q2;
  output r;
  reg r;
  always @*
    if (en) q = d;
  always @*
    if (!en) q2 = d;
  always @(posedge clk)
    r <= d;
endmodule
"""


def test_preflight_rejects_behavioural_latch_naming_the_line(tmp_path):
    """The shape the issue reports -- a `reg` declaration plus `always @*`
    block where `write_verilog` rendered a surviving unmapped latch --
    rejected up front with the construct, its line number, and the
    library-has-no-latch-cell fix, instead of OpenSTA's `STA-0171`."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;", "  wire net1;\n  reg q;\n  always @*\n    if (en) q = d;"
    )

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert "'reg'" in message
    assert "latch" in message
    assert "latch_map" in message
    assert "klt synthesize" in message
    assert "STA-0171" not in message


def test_preflight_rejects_a_bare_always_block_naming_the_line(tmp_path):
    """An `always` block on its own (a post-edited netlist whose `reg`
    declaration was already removed) is the same fatal construct."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;", "  wire net1;\n  always @*\n    if (en) q = d;"
    )

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert "'always'" in message


def test_preflight_reports_the_earlier_signed_decl_before_a_later_latch(tmp_path):
    """Test-plan edge case: a netlist carrying both a `signed` qualifier and
    a behavioural latch. Both are already fatal, so the first in file order
    is reported -- the same discipline the `signed`/x pair follows."""
    netlist = _CLEAN_NETLIST.replace(
        "  output [15:0] resp_msg;", "  output signed [15:0] resp_msg;"
    ).replace("  wire net1;", "  wire net1;\n  reg q;\n  always @*")

    message = _reject_message(tmp_path, netlist)

    assert "signed" in message
    assert "line 4" in message


def test_preflight_ignores_behavioural_constructs_in_comments(tmp_path):
    """Comment-aware: a Yosys banner block or `//` comment mentioning `reg`
    or `always` is prose, not a construct."""
    netlist = (
        "/* Generated by Yosys 0.67+post -- module carries a reg q;\n"
        " * and an always @* block, prose only\n"
        " */\n"
        "// reg [3:0] legacy;\n"
        "// always @(posedge clk) legacy <= legacy + 1;\n"
    ) + _CLEAN_NETLIST
    _write(tmp_path / "gcd_synth.v", netlist)

    place_and_route._reject_unsupported_netlist_constructs(
        str(tmp_path / "gcd_synth.v")
    )


def test_preflight_accepts_reg_substrings_and_instance_names(tmp_path):
    """No false positive on identifiers merely containing `reg`/`always` --
    Yosys names flop instances `_reg_0_`, nets `regbank_out` -- because the
    pattern is anchored to a line-start declaration, not a bare `\\breg\\b`."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;",
        "  wire net1;\n  wire regbank_out;\n"
        "  sky130_fd_sc_hd__dfxtp_1 _reg_0_ (.D(req_val), .CLK(clk), .Q(net1));\n"
        "  assign regbank_out = net1;",
    )
    _write(tmp_path / "gcd_synth.v", netlist)

    place_and_route._reject_unsupported_netlist_constructs(
        str(tmp_path / "gcd_synth.v")
    )


# ---- Issue #6274: attribution + SystemVerilog coverage ---------------------


def test_preflight_names_latch_cause_for_real_yosys_declaration_block_shape(tmp_path):
    """Regression guard for the evidence rule: in real Yosys output the `reg`
    declaration (line 11) is nowhere near its `always @*` block (line 16), so
    the latch narrative must key off the netlist carrying the unmapped-latch
    rendering, not off the flagged line sitting next to an `always @*`. The
    message still leads with the construct, line and offending text, and cites
    the line that is the evidence."""
    message = _reject_message(tmp_path, _YOSYS_UNMAPPED_LATCH_NETLIST)

    assert "line 11" in message
    assert "'reg'" in message
    assert "reg q;" in message
    assert "latch_map" in message
    assert "line 16" in message
    assert "STA-0171" not in message


@pytest.mark.parametrize(
    "body",
    [
        "if (!en) q = d;",
        "if (rst) q = 1'h0;\n    else if (en) q = d;",
    ],
    ids=["negative-enable", "async-reset"],
)
def test_preflight_keeps_latch_cause_for_yosys_latch_variants(tmp_path, body):
    """Negative-enable and reset-gated latches render the same way (`always
    @*` then a bare `if`), so they keep the latch narrative too."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;", f"  wire net1;\n  reg q;\n  always @*\n    {body}"
    )

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert "latch_map" in message


def test_preflight_rtl_flop_reg_gets_generic_message_not_latch_narrative(tmp_path):
    """The mis-attribution the issue measured: an RTL source (a flop `reg`
    clocked by `always @(posedge clk)`) handed over as the netlist. The
    construct, line and offending text are still named, but the cause is the
    generic 'this is behavioural source, not a structural netlist' -- no
    latch, no `latch_map`, no cell-library advice that cannot apply."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;",
        "  wire net1;\n  reg [15:0] acc;\n  always @(posedge clk)\n    acc <= acc + 1;",
    )

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert "'reg'" in message
    assert "reg [15:0] acc;" in message
    assert "RTL" in message
    assert "netlist_path" in message
    assert "klt synthesize" in message
    assert "latch" not in message.replace(str(tmp_path), "<tmp>")
    assert "STA-0171" not in message


def test_preflight_rtl_combinational_always_gets_generic_message(tmp_path):
    """A combinational RTL `always @(*)` block (`begin ... end` body) is not
    Yosys's unmapped-latch rendering (a bare `if` body), so it must not be
    narrated as one."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;",
        "  wire net1;\n  reg y;\n  always @(*)\n  begin\n    y = req_val & clk;\n  end",
    )

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert "'reg'" in message
    assert "latch" not in message.replace(str(tmp_path), "<tmp>")


@pytest.mark.parametrize(
    ("statement", "construct"),
    [
        ("always_ff @(posedge clk) q <= d;", "always_ff"),
        ("always_comb q = d;", "always_comb"),
        ("always_latch if (en) q = d;", "always_latch"),
        ("initial begin", "initial"),
        ("initial q = 1'b0;", "initial"),
    ],
)
def test_preflight_rejects_systemverilog_behavioural_forms(
    tmp_path, statement, construct
):
    """`always_ff`/`always_comb`/`always_latch` and `initial` previously fell
    through to OpenSTA's bare `STA-0171`; each is now rejected up front with
    the construct, line and offending text, and with the generic cause (none
    is Yosys's unmapped-latch rendering)."""
    netlist = _CLEAN_NETLIST.replace("  wire net1;", f"  wire net1;\n  {statement}")

    message = _reject_message(tmp_path, netlist)

    assert "line 7" in message
    assert f"'{construct}'" in message
    assert statement in message
    assert "latch_map" not in message
    assert "STA-0171" not in message


def test_preflight_accepts_keyword_prefixed_identifiers(tmp_path):
    """No false positive on names that merely *start with* a behavioural
    keyword -- `always_on_buf` (a module), `initialize_cell`, a continuation
    line beginning `initial_value` / `always_ff_q` -- because every keyword in
    the pattern is word-boundary terminated."""
    netlist = _CLEAN_NETLIST.replace(
        "  wire net1;",
        "  wire net1;\n  wire\n    initial_value,\n    always_ff_q;\n"
        "  always_on_buf _1_ (.A(net1), .Y(initial_value));\n"
        "  initialize_cell _2_ (.A(initial_value), .Y(always_ff_q));",
    )
    _write(tmp_path / "gcd_synth.v", netlist)

    place_and_route._reject_unsupported_netlist_constructs(
        str(tmp_path / "gcd_synth.v")
    )


def test_preflight_ignores_systemverilog_forms_in_comments(tmp_path):
    """Comment-aware for the widened pattern too: an `always_ff`/`initial`
    mentioned in a `//` or `/* */` comment is prose."""
    netlist = (
        "/* RTL was:\n"
        " *   always_ff @(posedge clk) q <= d;\n"
        " *   initial begin q = 0; end\n"
        " */\n"
        "// always_comb y = a;\n"
        "// always_latch if (en) q = d;\n"
    ) + _CLEAN_NETLIST
    _write(tmp_path / "gcd_synth.v", netlist)

    place_and_route._reject_unsupported_netlist_constructs(
        str(tmp_path / "gcd_synth.v")
    )


@pytest.mark.parametrize(
    "line",
    [
        "reg q;",
        "  reg [3:0] x, y;",
        "\treg\tq;",
        "always @*",
        "  always @(*)",
        "  always @(posedge clk)",
        "always@(*) begin",
    ],
)
def test_preflight_pattern_is_a_superset_of_the_synthesize_latch_pattern(line):
    """`klt synthesize`'s `netlist_behavioural_latch` warning keeps the narrow
    `reg`/`always` pattern (its latch narrative is only true for that shape;
    issue #6274 puts changing that warning out of scope), while the P&R
    pre-flight uses the wider one. The wider pattern must never miss a line
    the narrow one flags -- that would be a netlist synthesize warns about but
    P&R silently accepts."""
    assert netlist_construct_scan.NETLIST_BEHAVIOURAL_LATCH_RE.search(line)
    assert netlist_construct_scan._NETLIST_BEHAVIOURAL_RE.search(line)


@pytest.mark.parametrize(
    "line",
    [
        "always_ff @(posedge clk) q <= d;",
        "always_comb y = a;",
        "always_latch if (en) q = d;",
        "initial begin",
    ],
)
def test_synthesize_latch_pattern_stays_narrow(line):
    """The shared synthesize-time latch pattern is unchanged by #6274: the
    SystemVerilog forms are the pre-flight's own, wider net."""
    assert not netlist_construct_scan.NETLIST_BEHAVIOURAL_LATCH_RE.search(line)
    assert netlist_construct_scan._NETLIST_BEHAVIOURAL_RE.search(line)
