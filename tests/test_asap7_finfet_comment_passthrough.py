"""`adapt_extracted_netlist` copies ``*`` comment lines verbatim (#6020).

Split out of ``tests/test_asap7_finfet.py`` (at its 1627-line ratchet
ceiling) so the pin lives in its own module.
"""

from __future__ import annotations

from klayout_tools import asap7_bsimcmg


def test_adapt_extracted_netlist_passes_comment_lines_through_verbatim():
    """Issue #6020: `*` lines (including provenance headers) are copied
    unchanged, so a derived netlist inherits the source's authorship claims.
    Pins the pass-through so any change to it is deliberate and visible."""
    text = (
        "* Generated by klt extract 0.9.2; do not edit by hand.\n"
        "* second provenance line\n"
        "\n"
        ".SUBCKT X A Y VDD\n"
        "* mid-file comment after a blank line\n"
        "M1 A Y VDD VDD nmos_rvt L=0.02U W=0.1U NFIN=3\n"
        ".ENDS\n"
    )
    out = asap7_bsimcmg.adapt_extracted_netlist(text)
    lines = out.splitlines()
    # Header lines survive verbatim, in order, before and after a blank line.
    assert lines[0] == "* Generated by klt extract 0.9.2; do not edit by hand."
    assert lines[1] == "* second provenance line"
    assert lines[2] == ""
    assert lines[3] == ".SUBCKT X A Y VDD"
    assert lines[4] == "* mid-file comment after a blank line"
    assert lines[5] == "N1 A Y VDD VDD nmos_rvt L=0.02U NFIN=3"
    assert lines[6] == ".ENDS"
