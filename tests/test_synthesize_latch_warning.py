"""Surviving behavioural-latch disclosure (issue #5792): the written netlist
is scanned with the same regex `klt place-and-route`'s pre-flight uses, so a
netlist P&R will refuse -- a latch `write_verilog` had to render behaviourally
because the synthesis library has no latch cell for it -- is reported by
`klt synthesize` first, instead of surfacing later as a raw STA-0171."""

import json

import pytest

from klayout_tools.synthesize import run_synthesize
from klayout_tools.synthesize_x_scan import netlist_behavioural_latch_warning
from test_synthesize import _setup_success_env, _stub_yosys_success

pytestmark = pytest.mark.usefixtures("real_build_identity_git")

#: The shape `write_verilog -noattr` actually emits for a surviving
#: `$_DLATCH_N_`/`$_DLATCH_P_` (verified live, Yosys 0.67): a behavioural
#: `reg` declaration plus an `always @*` block, not a cell instance.
_LATCH_NETLIST_BODY = (
    "/* Generated by Yosys 0.67+post (git sha1 deadbeef) */\n"
    "\n"
    "module top(en, d, q);\n"
    "  input en;\n"
    "  wire en;\n"
    "  input d;\n"
    "  wire d;\n"
    "  output q;\n"
    "  reg q;\n"
    "  always @*\n"
    "    if (en) q = d;\n"
    "endmodule\n"
)


def test_surviving_behavioural_latch_adds_warning(tmp_path, monkeypatch):
    request_path = _setup_success_env(tmp_path, monkeypatch)
    _stub_yosys_success(monkeypatch, netlist_body=_LATCH_NETLIST_BODY)

    report = run_synthesize(request_path)

    assert report["warnings"]["by_category"]["netlist_behavioural_latch"] == 1
    advice = next(
        rep["text"]
        for rep in report["warnings"]["representatives"]
        if rep["category"] == "netlist_behavioural_latch"
    )
    assert "2 behavioural" in advice
    assert "line(s) 9, 10" in advice
    assert "'reg q;'" in advice
    assert "latch" in advice
    assert "latch_map" in advice
    assert "place-and-route" in advice


def test_clean_netlist_has_no_behavioural_latch_warning(tmp_path, monkeypatch):
    request_path = _setup_success_env(tmp_path, monkeypatch)
    _stub_yosys_success(
        monkeypatch, netlist_body="module gcd();\n  assign a = 8'hbe;\nendmodule\n"
    )

    report = run_synthesize(request_path)

    assert "netlist_behavioural_latch" not in json.dumps(report["warnings"])


def test_latch_map_mapped_run_emits_no_warning(tmp_path, monkeypatch):
    """The `latch_map`-mapped negative: with the latch mapped onto a library
    cell, `write_verilog` emits a cell instance (never behavioural
    statements) -- the clean shape, so no warning."""
    request_path = _setup_success_env(tmp_path, monkeypatch)
    _stub_yosys_success(
        monkeypatch,
        netlist_body=(
            "module top(en, d, q);\n"
            "  input en;\n"
            "  wire en;\n"
            "  input d;\n"
            "  wire d;\n"
            "  output q;\n"
            "  wire q;\n"
            "  sky130_fd_sc_hd__dlxtn_1 _0_ (.GATE_N(en), .D(d), .Q(q));\n"
            "endmodule\n"
        ),
    )

    report = run_synthesize(request_path)

    assert "netlist_behavioural_latch" not in json.dumps(report["warnings"])


def test_warning_names_first_five_lines_and_counts_the_rest():
    lines = ["module m();"]
    lines += [f"  reg q{i};" for i in range(8)]
    lines += ["endmodule"]

    warning = netlist_behavioural_latch_warning("\n".join(lines) + "\n")

    body = warning["netlist_behavioural_latch"]
    assert "8 behavioural" in body
    assert "line(s) 2, 3, 4, 5, 6" in body
    assert "(+3 more)" in body


def test_warning_is_empty_on_a_clean_netlist():
    assert netlist_behavioural_latch_warning("module m();\nendmodule\n") == {}


def test_warning_ignores_comment_mentions():
    """The same comment-awareness the P&R pre-flight has: a Yosys banner
    block or `//` comment mentioning `reg`/`always` is prose."""
    text = (
        "/* Generated by Yosys 0.67+post */\n"
        "// reg q; always @*\n"
        "module m();\n"
        "endmodule\n"
    )

    assert netlist_behavioural_latch_warning(text) == {}
