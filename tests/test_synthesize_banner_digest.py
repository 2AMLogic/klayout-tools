"""`netlist_sha256_banner_normalised` (issue #7277): the build-blind
companion to `netlist_sha256`.

Yosys's `write_verilog` emits its full version+build banner as the emitted
netlist's first line, and that banner names the compiler that built the
Yosys binary itself -- so two differently-built binaries at the *same*
version and git sha produce byte-identical netlists that hash differently
under the raw whole-file digest. The banner-normalised digest omits
exactly that first line and its LF or CRLF terminator and hashes every
remaining byte verbatim; without a matching first line it equals
`netlist_sha256`, which stays the exact-file integrity check (a banner-only
edit still drifts the raw check, including for reports that predate the
new field).

Split out of `tests/test_synthesize.py` to respect the per-file size
ratchet.
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path

import pytest

from klayout_tools import synthesize
from klayout_tools._digest import sha256_file_banner_normalised
from klayout_tools.synthesize import run_synthesize
from test_synthesize import (
    _GCD_RTL,
    _abs_path,
    _base_request,
    _isolate_pdk,
    _make_pdk_install,
    _record_yosys_scripts,
    _setup_success_env,
    _stub_yosys_success,
    _write,
    _write_report,
    _write_request,
)

pytestmark = pytest.mark.usefixtures("real_build_identity_git")

_GCC_BANNER_LINE = (
    "/* Generated by Yosys 0.67+post (git sha1 deadbeef, Release, "
    "GNU /usr/bin/c++ 13.3.0) */\n"
)
_CLANG_BANNER_LINE = (
    "/* Generated by Yosys 0.67+post (git sha1 deadbeef, Release, "
    "Clang /usr/bin/c++ 18.1.3) */\n"
)
_NETLIST_BODY = "module gcd(clk);\n  input clk;\nendmodule\n"


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


@pytest.fixture
def repo_path(tmp_path: Path) -> Path:
    """`tests/test_synthesize.py`'s own `tmp_path` override (which seeds a
    `.git` marker, issue #1844) is module-local; this reproduces it so
    `netlist_path` reports `scope: "repo"` and `_abs_path` applies here."""
    (tmp_path / ".git").mkdir()
    return tmp_path


# --- The digest helper, byte-precise -------------------------------------


def test_helper_hashes_bytes_after_lf_terminated_banner(tmp_path):
    netlist = tmp_path / "lf.v"
    netlist.write_bytes(_GCC_BANNER_LINE.encode() + b"rest\n")
    assert sha256_file_banner_normalised(str(netlist)) == _sha256(b"rest\n")


def test_helper_hashes_verbatim_bytes_after_crlf_terminated_banner(tmp_path):
    """A CRLF banner terminator is omitted whole; the remaining CRLF line
    endings are hashed verbatim, not rewritten."""
    body = b"module gcd(clk);\r\n  input clk;\r\nendmodule\r\n"
    netlist = tmp_path / "crlf.v"
    netlist.write_bytes(_GCC_BANNER_LINE.rstrip("\n").encode() + b"\r\n" + body)
    assert sha256_file_banner_normalised(str(netlist)) == _sha256(body)


def test_helper_hashes_whole_file_when_first_line_is_not_the_banner(tmp_path):
    """A bannerless file, an ordinary leading comment, a banner later in
    the file, and a banner not at byte zero (leading space) are all hashed
    whole -- only a first line consisting entirely of the banner at byte
    zero is omitted."""
    cases = {
        "bannerless.v": b"// fake mapped netlist\n",
        "ordinary_comment.v": b"/* ordinary comment */\nmodule top();\nendmodule\n",
        "banner_later.v": (
            b"module top();\n"
            b"/* Generated by Yosys 0.67+post (git sha1 x, g++) */\n"
            b"endmodule\n"
        ),
        "not_at_byte_zero.v": (
            b" /* Generated by Yosys 0.67+post (git sha1 x, g++) */\n"
            b"module top();\nendmodule\n"
        ),
    }
    for name, data in cases.items():
        path = tmp_path / name
        path.write_bytes(data)
        assert sha256_file_banner_normalised(str(path)) == _sha256(data), name


def test_helper_banner_only_file_hashes_empty_remainder(tmp_path):
    """A file that is nothing but the banner line hashes the empty
    remainder, with or without a final terminator."""
    for name, data in (
        ("lf.v", _GCC_BANNER_LINE.encode()),
        ("unterminated.v", _GCC_BANNER_LINE.rstrip("\n").encode()),
    ):
        path = tmp_path / name
        path.write_bytes(data)
        assert sha256_file_banner_normalised(str(path)) == _sha256(b""), name


def test_helper_missing_file_returns_none(tmp_path):
    assert sha256_file_banner_normalised(str(tmp_path / "absent.v")) is None
    assert sha256_file_banner_normalised(None) is None


# --- The report field, end to end against the stubbed Yosys --------------


def test_banner_only_build_difference_keeps_normalised_digest_stable(
    repo_path, monkeypatch
):
    """Two differently-built Yosys binaries at one version and git sha:
    different raw hashes, one shared normalised digest equal to an
    independent SHA-256 of the body bytes -- and one changed body byte
    changes it. The emitted file keeps its banner."""
    request_path = _setup_success_env(repo_path, monkeypatch)

    _stub_yosys_success(monkeypatch, netlist_body=_GCC_BANNER_LINE + _NETLIST_BODY)
    gcc_report = run_synthesize(request_path)

    _stub_yosys_success(monkeypatch, netlist_body=_CLANG_BANNER_LINE + _NETLIST_BODY)
    clang_report = run_synthesize(request_path)

    # The banner is still in the emitted bytes; both fields describe them.
    with open(_abs_path(gcc_report["netlist_path"], repo_path), "rb") as handle:
        assert handle.read() == (_GCC_BANNER_LINE + _NETLIST_BODY).encode()

    body_digest = _sha256(_NETLIST_BODY.encode())
    for report in (gcc_report, clang_report):
        digest = report["netlist_sha256_banner_normalised"]
        assert re.fullmatch(r"[0-9a-f]{64}", digest)
        assert digest == body_digest
    assert gcc_report["netlist_sha256"] == _sha256(
        (_GCC_BANNER_LINE + _NETLIST_BODY).encode()
    )
    assert clang_report["netlist_sha256"] == _sha256(
        (_CLANG_BANNER_LINE + _NETLIST_BODY).encode()
    )
    assert gcc_report["netlist_sha256"] != clang_report["netlist_sha256"]

    _stub_yosys_success(
        monkeypatch,
        netlist_body=_GCC_BANNER_LINE + _NETLIST_BODY.replace("input", "onput"),
    )
    edited_report = run_synthesize(request_path)
    assert edited_report["netlist_sha256_banner_normalised"] != body_digest


def test_without_banner_line_normalised_digest_equals_raw(repo_path, monkeypatch):
    """The stub's bannerless default netlist: the new digest equals
    `netlist_sha256`, the exact-file digest."""
    request_path = _setup_success_env(repo_path, monkeypatch)
    _stub_yosys_success(monkeypatch)

    report = run_synthesize(request_path)

    emitted = Path(_abs_path(report["netlist_path"], repo_path)).read_bytes()
    assert report["netlist_sha256_banner_normalised"] == report["netlist_sha256"]
    assert report["netlist_sha256_banner_normalised"] == _sha256(emitted)


def test_normalised_digest_present_for_external_redacted_path(
    tmp_path_factory, monkeypatch
):
    """Both fields describe the real output even when the report redacts
    its path (`scope: "external"`); the digest is verified against the
    emitted bytes."""
    no_repo_dir = tmp_path_factory.mktemp("no-repo-banner")
    _isolate_pdk(monkeypatch, no_repo_dir)
    install_root = no_repo_dir / "install"
    _make_pdk_install(install_root, "sky130A")
    monkeypatch.setenv("PDK_ROOT", str(install_root))
    _write(no_repo_dir / "gcd.v", _GCD_RTL)
    request_path = _write_request(no_repo_dir / "request.json", _base_request())
    _stub_yosys_success(monkeypatch, netlist_body=_GCC_BANNER_LINE + _NETLIST_BODY)
    scripts = _record_yosys_scripts(monkeypatch)

    report = run_synthesize(request_path)

    assert report["netlist_path"] == {"path": None, "scope": "external"}
    actual = [
        os.path.join(os.path.dirname(s), "gcd_synth.v")
        for s in scripts
        if not s.endswith("_baseline.ys")
    ]
    assert actual and os.path.isfile(actual[0])
    with open(actual[0], "rb") as handle:
        emitted = handle.read()
    assert emitted == (_GCC_BANNER_LINE + _NETLIST_BODY).encode()
    assert report["netlist_sha256"] == _sha256(emitted)
    assert report["netlist_sha256_banner_normalised"] == _sha256(_NETLIST_BODY.encode())


def test_normalised_digest_covers_stripped_signed_qualifiers(repo_path, monkeypatch):
    """The digest describes the final written file -- after the existing
    signed-qualifier rewrite -- not Yosys's raw output, mirroring
    `netlist_sha256`'s contract (issue #2452)."""
    request_path = _setup_success_env(repo_path, monkeypatch)
    _stub_yosys_success(
        monkeypatch,
        netlist_body=_GCC_BANNER_LINE
        + "module gcd(clk, sample);\n"
        + "  input clk;\n"
        + "  output signed [15:0] sample;\n"
        + "endmodule\n",
    )

    report = run_synthesize(request_path)

    stripped_body = (
        b"module gcd(clk, sample);\n  input clk;\n  output [15:0] sample;\nendmodule\n"
    )
    emitted = Path(_abs_path(report["netlist_path"], repo_path)).read_bytes()
    assert emitted == _GCC_BANNER_LINE.encode() + stripped_body
    assert report["netlist_sha256"] == _sha256(emitted)
    assert report["netlist_sha256_banner_normalised"] == _sha256(stripped_body)


def test_raw_digest_check_detects_banner_only_edit_on_older_report(
    repo_path, monkeypatch
):
    """The existing raw-hash integrity check still detects a banner-only
    edit -- including for a report that predates the new field (deleted
    here to simulate one); the unmodified copy still matches."""
    request_path = _setup_success_env(repo_path, monkeypatch)
    _stub_yosys_success(monkeypatch, netlist_body=_GCC_BANNER_LINE + _NETLIST_BODY)
    report = run_synthesize(request_path)
    del report["netlist_sha256_banner_normalised"]
    report_path = _write_report(repo_path / "gcd.synth.json", report)

    good = repo_path / "good.v"
    good.write_bytes(Path(_abs_path(report["netlist_path"], repo_path)).read_bytes())
    _first, _sep, rest = good.read_bytes().partition(b"\n")
    bad = repo_path / "bad.v"
    bad.write_bytes(_CLANG_BANNER_LINE.encode() + rest)

    ok = synthesize.check_synthesize_report(
        report_path, request_path, netlist_override=str(good)
    )
    assert ok["status"] == "match"

    drifted = synthesize.check_synthesize_report(
        report_path, request_path, netlist_override=str(bad)
    )
    assert drifted["status"] == "drifted"
    by_field = {c["field"]: c for c in drifted["checks"]}
    assert by_field["netlist_sha256"]["match"] is False
