"""Hard macros with no physical view: the ``ORD-2013`` hint and the
untimed black-box declaration (issue #5707).

``klt sta`` in ``verilog`` mode accepts a ``macros[]`` entry carrying only
``cell`` -- no ``lef``, no ``lib`` -- as an explicit, opt-in declaration
that the master has no physical view and must ``link_design`` as an
untimed black box: its delay and power are excluded from the reported
numbers. ``validate_macros`` only admits the form when the caller passes
``allow_blackbox=True``; every other verb and ``def`` mode keep requiring
the LEF, and :func:`reject_lefless_in_def` is what makes the ``def``-mode
rejection name the field to set.

This module holds that whole surface -- entry validation, the generated
pin-less stub LEF, the def-mode rejection, the response field and the
missing-master hint -- so :mod:`klayout_tools.macros` and
``post_route_sta`` each stay within their per-file size ceilings (the
ratchet gating every PR); they import from here the way they import every
other shared-core helper. It also hosts ``macro_liberty_paths``
(issue #2635's per-corner macro-liberty resolution), macros-record logic
``post_route_sta`` shed for the same reason.
``missing_lef_master_hint`` is re-exported from
:mod:`klayout_tools.macros` so its ``synthesize``/``place-and-route``
callers keep working unchanged.
"""

from __future__ import annotations

import os
import re
from typing import Any

#: The two accepted spellings of the per-corner liberty map, canonical
#: first. See :mod:`klayout_tools.macros`'s module docstring for why both
#: exist; a LEF-less entry may name neither.
_LIB_FIELD_ALIASES = ("lib", "liberty")

#: ``[ERROR ORD-2013] instance <inst> LEF master <cell> not found`` -- the
#: "macro referenced in the netlist but absent from ``request.macros``"
#: case. Captured so :func:`missing_lef_master_hint` can turn it into a
#: request-level instruction instead of leaving a caller to search the
#: OpenROAD source for what a LEF master is.
_ORD_2013_RE = re.compile(
    r"\[ERROR ORD-2013\]\s*instance\s+(?P<instance>\S+)\s+LEF master\s+"
    r"(?P<master>\S+)\s+not found"
)


def validate_blackbox_entry(
    entry: dict[str, Any], *, label: str, error_cls: type[Exception]
) -> dict[str, Any]:
    """One LEF-less ``macros[]`` entry (issue #5707): ``cell`` only."""
    cell = entry.get("cell")
    if not isinstance(cell, str) or not cell:
        raise error_cls(
            f"{label}.lef is required unless the entry declares an untimed "
            f'black box: give a non-empty "cell" and neither "lef" nor "lib"'
        )
    for name in (*_LIB_FIELD_ALIASES, "gds", "verilog_blackbox"):
        if entry.get(name) is not None:
            raise error_cls(
                f"{label}.{name} is not allowed without {label}.lef: an entry "
                f"with only a cell name is an untimed black box; supply the "
                "macro's lef as well to use a liberty, gds or blackbox view"
            )
    return {
        "cell": cell,
        "lef": None,
        "lib": None,
        "gds": None,
        "verilog_blackbox": None,
        "width_um": None,
        "height_um": None,
        "pins": [],
        "blackbox": True,
    }


def stub_lef_text(cell: str) -> str:
    """A pin-less LEF stub for an untimed black-box ``cell`` (issue #5707).

    Verified live against OpenROAD 26Q3: with this ``MACRO`` loaded,
    ``link_design`` succeeds and the instance stays an untimed cell (only
    ``STA-0201``/``ORD-2011`` warnings); without it ``link_design`` fails
    with ``ORD-2013`` even though OpenSTA itself creates a black box
    (``STA-0198``). The stub is deliberately pin-less -- connections to a
    port the stub does not declare are ignored by the engine."""
    return (
        "VERSION 5.8 ;\n"
        f"# Generated by klt for black-boxed cell '{cell}' -- do not edit.\n"
        f"MACRO {cell}\n"
        "  CLASS BLOCK ;\n"
        "  SIZE 1 BY 1 ;\n"
        f"END {cell}\n"
        "END LIBRARY\n"
    )


def blackboxed_cells_response(macros: list[dict[str, Any]]) -> list[dict[str, str]]:
    """``[{"cell": ...}]`` for every black-boxed entry, request order; ``[]``
    when none -- always a list, so a consumer never tests for presence."""
    return [{"cell": macro["cell"]} for macro in macros if macro.get("blackbox")]


def write_stub_lefs(
    macros: list[dict[str, Any]], output_dir: str, script_tag: str
) -> list[str]:
    """One ``blackbox_<script_tag>_<index>.lef`` per LEF-less entry
    (issue #5707), written into ``output_dir`` so ``link_design`` resolves
    the master.

    ``index`` counts the LEF-less entries in request order; the caller
    appends the returned paths after every declared macro LEF, and each
    ``read_lef`` lands before ``link_design`` in the generated script.
    """
    stub_paths = []
    for index, macro in enumerate(m for m in macros if m["lef"] is None):
        stub_path = os.path.join(output_dir, f"blackbox_{script_tag}_{index}.lef")
        with open(stub_path, "w", encoding="utf-8") as handle:
            handle.write(stub_lef_text(macro["cell"]))
        stub_paths.append(stub_path)
    return stub_paths


def reject_lefless_in_def(macros: Any, *, error_cls: type[Exception]) -> None:
    """Reject a LEF-less ``macros[]`` entry in ``def`` mode (issue #5707):
    a DEF carries placed geometry, so a macro cannot be declared an
    untimed black box there -- the error names the field to set. A
    non-list ``macros`` is left to the shared validator's own reporting.
    """
    if not isinstance(macros, list):
        return
    for index, entry in enumerate(macros):
        if isinstance(entry, dict) and entry.get("lef") is None:
            raise error_cls(
                f"request.macros[{index}].lef is required in def mode: a "
                "DEF carries placed geometry, so a macro cannot be "
                "declared as an untimed black box without a LEF (that "
                "form is verilog mode only)"
            )


def macro_liberty_paths(
    macros: list[dict[str, Any]], corner: str, *, error_cls: type[Exception]
) -> list[str]:
    """The macro liberties to ``read_liberty`` alongside the standard-cell
    library for the corner actually being analysed (issue #2635).

    A macro that declared no ``lib`` at all contributes nothing: its LEF is
    what fixes ``ORD-2013``, and OpenSTA then times the instance as an
    untimed blackbox (``[WARNING STA-0198] module <cell> not found.
    Creating black box for <inst>``) -- a legitimate, explicit choice for a
    caller doing a geometry-only run. A macro that *did* declare a ``lib``
    map with no entry for this corner is a hard error naming the corner and
    the keys that are available
    (:func:`~klayout_tools.macros.macro_lib_for_corner`), never a silent
    fallback to some other corner's timing -- which matters most in a
    ``request.pdk.corners`` multi-corner run, where the right answer for
    one corner is the wrong answer for the next.
    """
    # Deferred: macros.py imports this module at the top level, so a
    # top-level import back would be a partial-initialization cycle.
    from klayout_tools import macros as macros_module

    paths: list[str] = []
    for macro in macros:
        lib_path = macros_module.macro_lib_for_corner(
            macro, corner, error_cls=error_cls
        )
        if lib_path is not None:
            paths.append(lib_path)
    return paths


def missing_lef_master_hint(
    text: str, *, field: str = "request.macros", blackbox_form: bool = False
) -> str | None:
    """``None``, or an actionable hint that an OpenROAD run failed because
    the netlist instantiates a master no ``read_lef`` ever loaded -- the
    ``ORD-2013`` shape.

    Issue #2635's test plan calls this out explicitly: "a macro referenced
    in the netlist but absent from ``request.macros`` must still produce a
    clear, named error rather than ``ORD-2013``". ``ORD-2013`` names the
    instance and the master but says nothing about *which request field*
    would have supplied it, and the master name is exactly the ``cell``
    value the caller needs -- so the hint restates it as the request edit to
    make.

    ``blackbox_form`` (issue #5707, ``klt sta`` verilog mode only) also
    names the LEF-less ``{"cell": ...}`` declaration, which only that mode
    accepts -- so no other verb or mode ever suggests it.
    """
    match = _ORD_2013_RE.search(text)
    if match is None:
        return None
    master = match.group("master")
    instance = match.group("instance")
    hint = (
        f"instance '{instance}' is a hard macro ('{master}') with no "
        f"physical view loaded: declare it in {field} as "
        f'{{"cell": "{master}", "lef": "<{master}.lef>"}} (add a per-corner '
        '"lib" to time it too)'
    )
    if blackbox_form:
        hint += (
            f'; with no LEF at all, declare {{"cell": "{master}"}} alone to '
            "link it as an untimed black box (its delay and power are then "
            "excluded from the reported numbers)"
        )
    return hint
