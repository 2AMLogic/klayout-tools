"""Gate-level power-up state control for ``klt functional-verification``
(``options.initial_state``, issue #2998).

Silicon flops do not power up at 0, but a cell-model UDP's state cannot be
written through VPI, so a testbench cannot just "set the flops". This module
generates the Verilog-side form of the workaround downstream projects
hand-built in cocotb: for every sequential instance of the gate-level
netlist, hierarchically ``force`` its ``D`` pin to the requested value
(``x`` or one seeded-random bit), let the testbench's own clock take one
full cycle so the flop captures it, then release. The flop list is derived
from the netlist and the PDK cell models
(:func:`klayout_tools.reset_coverage.sequential_elements`), never hand-built.

Only ``D`` is forced -- never the clock or an asynchronous control. Releasing
a force on a net discards what the testbench deposited there meanwhile, and a
released clock or reset reads ``x``, which the real cell UDPs turn into an
unknown state; ``D`` alone is released onto a net whose driver is already
known. The window is the first full *real* clock cycle
(``negedge``, ``posedge``, ``negedge`` of the clock net, so a driver's first
undriven-to-level transition cannot be mistaken for a capturing edge); a
flop whose asynchronous reset is asserted during it simply stays reset.

The generated file is a second Icarus elaboration root
(:data:`INITIAL_STATE_MODULE`) so the DUT, its testbench and its
``hdl_toplevel`` are untouched. The seed is not baked into the file: it is
read from the ``+klt_init_seed=<n>`` plusarg, so one build serves every seed
and the same seed always reproduces the same state (``$random(seed)`` is
deterministic).

**Limits.** (1) Flops that share a ``D`` net share a value: Icarus collapses
connected ports into one net, so forcing ``inst.D`` forces every pin on it.
The drive draws once per distinct ``D`` net (in netlist order) -- the
response's ``state_elements`` counts instances, ``d_nets`` independent draws.
(2) A value the testbench writes straight onto a flop's ``D`` net during the
first clock cycle is lost on release; write stimulus after that cycle.
"""

from __future__ import annotations

import re
from typing import Any

INITIAL_STATE_MODULE = "klt_initial_state"
SEED_PLUSARG = "klt_init_seed"

_SIMPLE_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*$")


def _component(name: str) -> str:
    """One hierarchical path component, as an escaped identifier when the
    name is not a plain Verilog identifier (a flattened ``a/b[0]`` name)."""
    if _SIMPLE_IDENT_RE.match(name):
        return name
    return f"\\{name} "


def _path(scope: str, instance: str, pin: str) -> str:
    return f"{scope}.{_component(instance)}.{pin}"


_BIT_SELECT_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_$]*)\[(\d+)\]$")


def _net_reference(name: str) -> str:
    """A net name as a Verilog reference: a plain identifier or a bit select
    as written, anything else (a flattened ``a/b.c`` name) escaped."""
    if _SIMPLE_IDENT_RE.match(name) or _BIT_SELECT_RE.match(name):
        return name
    return f"\\{name} "


def _d_groups(elements: list[dict[str, Any]]) -> list[int]:
    """Per element, the index of its independent-draw group: elements whose
    ``D`` connects to the same (non-constant) net share one."""
    groups: list[int] = []
    seen: dict[str, int] = {}
    count = 0
    for element in elements:
        net = element.get("d_net")
        if not isinstance(net, str) or net.startswith("__CONST"):
            groups.append(count)
            count += 1
        elif net in seen:
            groups.append(seen[net])
        else:
            seen[net] = count
            groups.append(count)
            count += 1
    return groups


def count_d_nets(elements: list[dict[str, Any]]) -> int:
    """How many independent initial values the drive draws for ``elements``."""
    groups = _d_groups(elements)
    return max(groups) + 1 if groups else 0


def build_initial_state_verilog(
    *,
    mode: str,
    elements: list[dict[str, Any]],
    scope: str,
    clock: str,
) -> str:
    """The text of the generated ``klt_initial_state`` module. ``scope`` is
    the hierarchical path of the netlist's top module in the elaborated
    design; ``clock`` is the name of the net (in that module) whose first
    full cycle captures the forced values."""
    groups = _d_groups(elements)
    lines = [
        "// Generated by klt functional-verification (options.initial_state).",
        f"module {INITIAL_STATE_MODULE};",
        "  integer klt_seed;",
        "  integer klt_draw;",
    ]
    if mode == "random":
        # One reg per independent D net: a forced reg is a continuous drive
        # that tracks the reg, so a shared one would give every flop its
        # last draw.
        lines += [f"  reg klt_bit_{i};" for i in range(count_d_nets(elements))]
    lines.append("  initial begin")
    if mode == "random":
        lines.append(f'    if (!$value$plusargs("{SEED_PLUSARG}=%d", klt_seed))')
        lines.append("      klt_seed = 0;")
    drawn: set[int] = set()
    for element, index in zip(elements, groups, strict=True):
        d_path = _path(scope, element["instance"], element["d_pin"])
        if mode == "x":
            lines.append(f"    force {d_path} = 1'bx;")
            continue
        if index not in drawn:
            drawn.add(index)
            lines.append("    klt_draw = $random(klt_seed);")
            lines.append(f"    klt_bit_{index} = klt_draw[16];")
        lines.append(f"    force {d_path} = klt_bit_{index};")
    clock_path = f"{scope}.{_net_reference(clock)}"
    lines += [
        f"    @(negedge {clock_path});",
        f"    @(posedge {clock_path});",
        f"    @(negedge {clock_path});",
    ]
    for element in elements:
        lines.append(
            f"    release {_path(scope, element['instance'], element['d_pin'])};"
        )
    lines += ["  end", "endmodule", ""]
    return "\n".join(lines)
