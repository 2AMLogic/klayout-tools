"""ASAP7 BSIM-CMG adaptation for ngspice OSDI simulation (issue #2814).

``klt extract --deck asap7`` writes FinFET cards the way the PDK's own CDL
does (``M<name> d g s b <model> L=..U W=..U NFIN=<n>``), and lambdapdk's
``asap7/base/spice/hspice/7nm_*_160803.pm`` carries the HSPICE BSIM-CMG
model cards (``.model nmos_rvt nmos level = 72 ... version = 107``). Neither
loads in ngspice as written:

* ngspice has no built-in BSIM-CMG (``level = 72``); it runs BSIM-CMG only as
  an OSDI module (``bsimcmg_va``) compiled from the CMC Verilog-A source by
  ``scripts/fetch-asap7-sim-toolchain.sh`` and preloaded through
  ``options.osdi_preload``. An OSDI model card names the *module*, not a
  level, and an OSDI instance is an ``N`` element, not an ``M`` element.
* The Verilog-A module has no ``level`` or ``version`` parameter (the card's
  ``version = 107`` selects behaviour inside the HSPICE built-in; the
  module is BSIM-CMG 111.0.0) and takes the polarity as ``type`` (+1 NMOS,
  -1 PMOS).
* BSIM-CMG's geometry is quantised: the instance has ``L`` and ``NFIN`` (and
  ``NF`` fingers) but **no ``W``**. The extractor's ``W`` is derived from the
  fin count (informational), so it is dropped; ``NFIN`` stays the *total* fin
  count and ``NF`` is never written (it would multiply ``NFIN``).

This module is the one place that adaptation lives. It is pure text-to-text
and needs neither the PDK nor the toolchain, so the card contract is unit
tested without a download.
"""

from __future__ import annotations

import re

#: Verilog-A module name the OSDI binary exposes (``module bsimcmg_va`` in
#: the pinned CMC source); the model card's second token must equal it.
OSDI_MODULE = "bsimcmg_va"

#: HSPICE model-card tokens with no counterpart in the Verilog-A module.
_DROPPED_MODEL_PARAMS = frozenset({"level", "version"})

#: Polarity keyword -> the module's ``type`` parameter value.
_POLARITY_TYPE = {"nmos": 1, "pmos": -1}

_MODEL_HEAD_RE = re.compile(
    r"^\.model\s+(?P<name>\S+)\s+(?P<polarity>nmos|pmos)\b(?P<rest>.*)$",
    re.IGNORECASE,
)
_PARAM_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([^\s=]+)")
_M_CARD_RE = re.compile(r"^M(?P<name>\S+)\s+(?P<body>.*)$", re.IGNORECASE)

#: Model-card parameters per continuation line in the emitted cards.
_PARAMS_PER_LINE = 6


def _logical_lines(text: str) -> list[str]:
    """Join ``+`` continuations and drop ``*`` comment / blank lines."""
    logical: list[str] = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("*"):
            continue
        if line.startswith("+") and logical:
            logical[-1] += " " + line[1:].strip()
        else:
            logical.append(line)
    return logical


def adapt_model_cards(hspice_text: str) -> str:
    """Rewrite lambdapdk's HSPICE ``level = 72`` cards as ngspice OSDI cards.

    Each ``.model <name> nmos|pmos level = 72 ...`` becomes
    ``.model <name> bsimcmg_va type=<+1|-1> ...`` with ``level`` and
    ``version`` removed; every other parameter is carried over verbatim, so
    the electrical content of the card is untouched. Non-BSIM-CMG cards are
    refused rather than passed through, so a wrong input cannot yield a
    plausible-looking deck.
    """
    out: list[str] = [
        "* ASAP7 BSIM-CMG cards adapted for ngspice OSDI "
        f"(module {OSDI_MODULE}); generated by klayout_tools.asap7_bsimcmg"
    ]
    found = 0
    for line in _logical_lines(hspice_text):
        head = _MODEL_HEAD_RE.match(line)
        if head is None:
            continue
        params = [
            (key.lower(), value) for key, value in _PARAM_RE.findall(head["rest"])
        ]
        level = dict(params).get("level")
        if level is None or float(level) != 72:
            raise ValueError(
                f"model {head['name']!r} is not a BSIM-CMG level = 72 card "
                f"(level = {level!r}); refusing to adapt it"
            )
        kept = [(k, v) for k, v in params if k not in _DROPPED_MODEL_PARAMS]
        polarity = head["polarity"].lower()
        out.append(
            f".model {head['name']} {OSDI_MODULE} type={_POLARITY_TYPE[polarity]}"
        )
        for i in range(0, len(kept), _PARAMS_PER_LINE):
            chunk = kept[i : i + _PARAMS_PER_LINE]
            out.append("+ " + " ".join(f"{k}={v}" for k, v in chunk))
        found += 1
    if not found:
        raise ValueError("no BSIM-CMG `.model ... level = 72` cards found")
    return "\n".join(out) + "\n"


def _sanitize_names(line: str) -> str:
    """KLayout writes ``\\$11`` / ``VDD$1`` style names; ngspice rejects the
    backslash escape, so ``\\`` is dropped and ``$`` becomes ``_`` -- applied
    uniformly to every non-comment line so connectivity is unchanged."""
    return line.replace("\\", "").replace("$", "_")


def corner_library(sections: dict[str, str]) -> str:
    """Wrap adapted model text as a ``klt sim`` corner library.

    ``sections`` maps a corner name (``"tt"``, ``"ff"``, ``"ss"``) to the
    output of :func:`adapt_model_cards`; the result has one
    ``.lib <name> ... .endl <name>`` block per corner, so the request's
    ``models.lib`` plus ``corners.process`` selects the PVT corner and a
    multi-corner run is an ordinary ``klt sim`` sweep.
    """
    blocks = []
    for name, text in sections.items():
        blocks.append(f".lib {name}\n{text.rstrip()}\n.endl {name}\n")
    return "\n".join(blocks)


def adapt_extracted_netlist(spice_text: str) -> str:
    """Rewrite ``klt extract`` FinFET ``M`` cards as OSDI ``N`` instances.

    ``M<name> d g s b <model> L=.. W=.. NFIN=..`` becomes
    ``N<name> d g s b <model> L=.. NFIN=..``: the element letter selects the
    OSDI device, ``W`` is dropped (BSIM-CMG has no ``W``) and ``NFIN`` is
    passed through unchanged as the total fin count. A card without ``NFIN``
    is refused -- it is not a FinFET card and defaulting to one fin would
    silently simulate the wrong device.
    """
    out: list[str] = []
    for raw in spice_text.splitlines():
        if not raw.strip().startswith("*"):
            raw = _sanitize_names(raw)
        match = _M_CARD_RE.match(raw.strip())
        if match is None:
            out.append(raw)
            continue
        tokens = match["body"].split()
        params = {
            k.upper(): v for k, v in (t.split("=", 1) for t in tokens if "=" in t)
        }
        nodes = [t for t in tokens if "=" not in t]
        if len(nodes) != 5:
            raise ValueError(f"unexpected FinFET card shape: {raw.strip()!r}")
        if "NFIN" not in params:
            raise ValueError(f"FinFET card has no NFIN: {raw.strip()!r}")
        for forbidden in ("NF", "FINGERS", "AS", "AD", "PS", "PD"):
            if forbidden in params:
                raise ValueError(
                    f"FinFET card carries {forbidden}= which would be "
                    f"mis-scaled by BSIM-CMG: {raw.strip()!r}"
                )
        geometry = f"L={params['L']} " if "L" in params else ""
        out.append(
            f"N{match['name']} {' '.join(nodes)} {geometry}NFIN={params['NFIN']}"
        )
    return "\n".join(out) + ("\n" if spice_text.endswith("\n") else "")
