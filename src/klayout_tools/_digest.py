"""SHA-256 digest helpers shared by the verbs' provenance envelopes.

Re-exported from :mod:`klayout_tools._provenance`, which stays the public
home of these names.
"""

from __future__ import annotations

import hashlib
import os
import re

#: Issue #7277: the banner line `write_verilog` emits as a netlist's first
#: line. It names the compiler that built the Yosys binary itself, so the
#: raw whole-file digest differs across builds of the same version.
_YOSYS_BANNER_PREFIX = b"/* Generated by Yosys "


def normalize_sha256(value: object) -> str | None:
    """Return a lowercase 64-hex digest, or None for malformed evidence."""
    if isinstance(value, str) and re.fullmatch(r"[0-9a-fA-F]{64}", value):
        return value.lower()
    return None


def sha256_file(path: str | None) -> str | None:
    """Streamed SHA-256 hex digest of the file at ``path``, or ``None``.

    Returns ``None`` for a falsy path or one that is not an existing file --
    the defensive shape ``sim.py`` already relied on, now shared by every
    caller (``lvs``/``extract`` only pass paths that exist at hash time, so
    the guard is a no-op there).
    """
    if not path or not os.path.isfile(path):
        return None
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def sha256_file_banner_normalised(path: str | None) -> str | None:
    """SHA-256 of the file at ``path`` with a leading Yosys banner line
    omitted (issue #7277).

    Yosys's ``write_verilog`` emits ``/* Generated by Yosys <version> (git
    sha1 <sha>, <mode>, <compiler>) */`` as the netlist's first line, and
    that banner names the compiler that built Yosys itself -- so two
    differently-built binaries at the same version and git sha write
    byte-identical netlists that hash differently under
    :func:`sha256_file`. This digest omits that first line and its LF or
    CRLF terminator and hashes every remaining byte verbatim, giving the
    ``synthesize`` envelope a build-blind companion to the exact-file
    digest. A file whose first line is not entirely that one comment at
    byte zero is hashed whole, so the digest equals :func:`sha256_file`'s;
    a banner appearing later in the file is ordinary content. Returns
    ``None`` under the same conditions as :func:`sha256_file`.
    """
    if not path or not os.path.isfile(path):
        return None
    with open(path, "rb") as handle:
        first = handle.readline()
        line = first[:-1] if first.endswith(b"\n") else first
        if line.endswith(b"\r"):
            line = line[:-1]
        digest = hashlib.sha256()
        # Only the first closing delimiter can end the banner comment.
        is_banner = (
            line.startswith(_YOSYS_BANNER_PREFIX) and line.find(b"*/") == len(line) - 2
        )
        if not is_banner:
            digest.update(first)
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def netlist_digest_fields(netlist_path: str) -> dict[str, str | None]:
    """The ``synthesize`` envelope's netlist digest pair, for spreading into
    the response (``**netlist_digest_fields(path)``) — same shape as
    ``synthesize_timeout.timeout_fields``.

    ``netlist_sha256`` (issue #2452): SHA-256 of the exact bytes of the file
    ``netlist_path`` refers to, taken from the internal absolute path (never
    the redacted ``{path, scope}`` object) after signed-qualifier stripping.
    ``netlist_sha256_banner_normalised`` (issue #7277): its build-blind
    companion from :func:`sha256_file_banner_normalised`. Both additive;
    no ``schema_version`` bump.
    """
    return {
        "netlist_sha256": sha256_file(netlist_path),
        "netlist_sha256_banner_normalised": sha256_file_banner_normalised(netlist_path),
    }


def sha256_file_required(path: str) -> str:
    """:func:`sha256_file` for a path that must exist: raises
    ``FileNotFoundError`` instead of returning ``None``."""
    digest = sha256_file(path)
    if digest is None:
        raise FileNotFoundError(path)
    return digest


def content_hash(path: str | None) -> str | None:
    """The envelope's ``sha256:``-prefixed deck-hash form of ``path``, or
    ``None`` when the file can't be hashed."""
    digest = sha256_file(path)
    return f"sha256:{digest}" if digest is not None else None


def content_hash_required(path: str) -> str:
    """:func:`content_hash` for a path that must exist: raises
    ``FileNotFoundError`` instead of returning ``None``."""
    return "sha256:" + sha256_file_required(path)


def content_hash_bytes(data: bytes) -> str:
    """The ``sha256:``-prefixed digest of in-memory ``data``."""
    return "sha256:" + hashlib.sha256(data).hexdigest()
